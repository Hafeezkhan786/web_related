from odoo import models, fields, api
from odoo.exceptions import UserError
import requests
import json
import logging
import time

_logger = logging.getLogger(__name__)


class PosOrder(models.Model):
    _inherit = 'pos.order'

    fbr_invoice_number = fields.Char(
        string='FBR Invoice Number',
        readonly=True,
        copy=False,
        help='Invoice number generated by FBR POS system'
    )
    fbr_status = fields.Selection([
        ('draft', 'Draft'),
        ('posted', 'Posted to FBR'),
        ('failed', 'Failed'),
        ('pending', 'Pending Response'),
    ], string='FBR Status', default='draft', copy=False)
    fbr_error_message = fields.Text(
        string='FBR Error Message',
        readonly=True,
        help='Error message from FBR POS system'
    )
    fbr_response = fields.Text(
        string='FBR Response',
        readonly=True,
        help='Full response from FBR POS system'
    )
    fbr_payload = fields.Text(
        string='FBR Payload',
        readonly=True,
        help='Data sent to FBR POS system'
    )

    def action_pos_order_paid(self):
        """Override to automatically send order data to FBR POS after validation"""
        # Allow invoice generation (commented out hardcoded False)
        # self.to_invoice = False
        
        res = super(PosOrder, self).action_pos_order_paid()
        
        # Automatically post to FBR after validation
        if self.config_id.fbr_pos_integration and self.fbr_status != 'posted':
            print('Automatic FBR posting after validation for order:', self.name)
            self._send_to_fbr_pos()
        
        return res

    def _send_to_fbr_pos(self, force=False):
        """Send order data to FBR POS system"""
        self.ensure_one()
        print('_send_to_fbr_pos', self.config_id.fbr_pos_integration)
        if not force and not self.config_id.fbr_pos_integration:
            return
        
        # Get URL and Token based on environment
        if self.config_id.fbr_environment == 'testing':
            print('testing', self.config_id.fbr_pos_url, self.config_id.fbr_pos_id, self.config_id.fbr_branch_code)
            if not self.config_id.fbr_pos_url or not self.config_id.fbr_pos_id or not self.config_id.fbr_branch_code:
                raise UserError('For Testing: FBR POS URL, POS ID, and Branch Code must be configured in POS settings.')
            api_url = self.config_id.fbr_pos_url
            api_token = None  # No token required for testing
        else:  # production
            if not self.config_id.fbr_production_url or not self.config_id.fbr_production_token:
                print('production', self.config_id.fbr_production_url, self.config_id.fbr_production_token)
                raise UserError('For Production: FBR Production URL and Token must be configured in POS settings.')
            api_url = self.config_id.fbr_production_url
            api_token = self.config_id.fbr_production_token
        
        # Prepare payload for FBR POS
        payload = self._prepare_fbr_pos_payload()

        print('payload', payload)
        
        # Store payload for debugging
        self.sudo().write({'fbr_payload': json.dumps(payload, indent=2)})
        
        # Prepare headers
        headers = {
            'Content-Type': 'application/json',
        }
        
        # Add Authorization header only if token is provided
        if api_token:
            headers['Authorization'] = f'Bearer {api_token}'
        
        try:
            # Send request to FBR POS
            response = requests.post(
                api_url,
                json=payload,
                headers=headers,
                timeout=self.config_id.fbr_pos_timeout
            )
            
            # Store response
            response_data = response.json() if response.content else {}


            self.sudo().write({'fbr_response': json.dumps(response_data, indent=2)})
            print('response_data',response_data)
            print('status_code ',response.status_code )
            # Process response
            if response.status_code  == 200:
                # Handle different response formats
                if isinstance(response_data, dict):
                    if  response_data.get('InvoiceNumber'):
                        invoice_number = response_data.get('InvoiceNumber')
                        self.sudo().write({
                            'fbr_invoice_number': invoice_number,
                            'fbr_status': 'posted',
                            'fbr_error_message': response_data.get('Errors') if response_data.get('Errors') else '',
                        })
                        _logger.info('Order %s successfully posted to FBR POS with invoice number %s', 
                                   self.name, invoice_number)
                    else:
                        error_msg = response_data.get('error') or response_data.get('message') or 'Unknown error from FBR POS'
                        self.sudo().write({
                            'fbr_status': 'failed',
                            'fbr_error_message': error_msg,
                        })
                        _logger.error('FBR POS returned error for order %s: %s', self.name, error_msg)
                else:
                    # If response is just a string (invoice number)
                    self.sudo().write({
                        'fbr_invoice_number': str(response_data),
                        'fbr_status': 'posted',
                        'fbr_error_message': '',
                    })
                    _logger.info('Order %s successfully posted to FBR POS with invoice number %s', 
                               self.name, str(response_data))
            else:
                error_msg = f'HTTP {response.status_code}: {response.text}'
                self.sudo().write({
                    'fbr_status': 'failed',
                    'fbr_error_message': error_msg,
                })
                _logger.error('FBR POS returned error for order %s: %s', self.name, error_msg)
                
        except requests.exceptions.Timeout:
            error_msg = f'FBR POS request timed out after {self.config_id.fbr_pos_timeout} seconds'
            self.sudo().write({
                'fbr_status': 'failed',
                'fbr_error_message': error_msg,
            })
            _logger.error('FBR POS timeout for order %s', self.name)
            
        except requests.exceptions.RequestException as e:
            error_msg = f'Network error connecting to FBR POS: {str(e)}'
            self.sudo().write({
                'fbr_status': 'failed',
                'fbr_error_message': error_msg,
            })
            _logger.error('Network error for order %s: %s', self.name, str(e))
            
        except Exception as e:
            error_msg = f'Unexpected error: {str(e)}'
            self.sudo().write({
                'fbr_status': 'failed',
                'fbr_error_message': error_msg,
            })
            _logger.error('Unexpected error for order %s: %s', self.name, str(e))

    def _prepare_fbr_pos_payload(self):
        """Prepare payload data for FBR POS API using the exact JSON schema provided"""
        self.ensure_one()

        # Determine Invoice Type and RefUSIN for return/refund orders
        is_return = any(line.qty < 0 for line in self.lines) or self.amount_total < 0
        invoice_type = 3 if is_return else 1

        ref_usin = None
        refunded_lines = self.lines.filtered(lambda l: l.refunded_orderline_id)
        if refunded_lines:
            original_order = refunded_lines[0].refunded_orderline_id.order_id
            ref_usin = original_order.fbr_invoice_number or f"USIN{original_order.id}"

        # 1. Prepare the Items List
        items = []
        for line in self.lines:
            # Calculate item specific taxes and discount
            tax_rate = line.tax_ids_after_fiscal_position[0].amount if line.tax_ids_after_fiscal_position else 0.0
            tax_charged = line.price_subtotal_incl - line.price_subtotal
            
            # Calculate true discount amount (pricelist + manual)
            original_price_unit = max(line.product_id.lst_price, line.price_unit)
            selling_price_unit = line.price_unit * (1 - line.discount / 100.0)
            discount_amount = (original_price_unit - selling_price_unit) * line.qty

            # Get PCT Code if saved on product, otherwise use fallback
            pct_code = getattr(line.product_id, 'pct_code', '11001010')

            items.append({
                "ItemCode": line.product_id.default_code or f"IT_{line.product_id.id}",
                "ItemName": line.product_id.name,
                "Quantity": line.qty,
                "PCTCode": pct_code or "11001010",
                "TaxRate": tax_rate,
                "SaleValue": line.price_subtotal,
                "TotalAmount": line.price_subtotal_incl,
                "TaxCharged": tax_charged,
                "Discount": discount_amount,
                "FurtherTax": 0.0,      # Fill if you use FBR's Further Tax laws
                "InvoiceType": invoice_type,       # 1 = Sale, 2 = Debit Note, 3 = Credit Note
                "RefUSIN": ref_usin
            })
            print('items', items)

        # 2. Extract Customer Information
        buyer_ntn = ""
        buyer_cnic = ""
        buyer_phone = ""
        buyer_name = "Walking Customer"

        if self.partner_id:
            buyer_name = self.partner_id.name
            buyer_phone = self.partner_id.phone or "0000-0000000"
            # Assuming you have custom/standard fields for CNIC and NTN on res.partner
            buyer_ntn = getattr(self.partner_id, 'vat', '')
            buyer_cnic = getattr(self.partner_id, 'cnic', '')

        # 3. Compile the Final Payload
        payload = {
            "InvoiceNumber": "",        # Leave empty, FBR will return this
            "POSID": int(self.config_id.fbr_pos_id) if self.config_id.fbr_pos_id else 0,
            "USIN": f"USIN{self.id}",    # Unique internal system number (e.g., Odoo DB ID)
            "DateTime": self.date_order.strftime('%Y-%m-%d %H:%M:%S'),
            "BuyerNTN": buyer_ntn or None,
            "BuyerCNIC": buyer_cnic or None,
            "BuyerName": buyer_name,
            "BuyerPhoneNumber": buyer_phone,
            "TotalBillAmount": self.amount_total,
            "TotalQuantity": sum(self.lines.mapped('qty')),
            "TotalSaleValue": self.amount_total - self.amount_tax,
            "TotalTaxCharged": self.amount_tax,
            "Discount": sum(items[i]['Discount'] for i in range(len(items))),
            "FurtherTax": 0.0,
            "PaymentMode": 1,           # 1 = Cash, 2 = Card, etc.
            "RefUSIN": ref_usin,
            "InvoiceType": invoice_type,           # 1 = Sale, 3 = Credit Note (Return)
            "Items": items
        }

        print(payload)

        return payload

    def action_print_fbr_receipt(self):
        """Print FBR Receipt using custom template"""
        for order in self:
            if order.fbr_status == 'posted' and order.fbr_invoice_number:
                return self.env.ref('sng_pos_fbr_integration.fbr_pos_receipt_action').report_action(order)
            else:
                raise UserError('FBR Receipt can only be printed for orders that are successfully posted to FBR.')
    
    def action_retry_fbr_post(self):
        """Manual FBR posting triggered by 'Post To FBR' button or Action menu"""
        posted_count = 0
        failed_orders = []
        for order in self:
            if order.fbr_status == 'posted':
                continue
            order._send_to_fbr_pos(force=True)
            if order.fbr_status == 'posted':
                posted_count += 1
            else:
                failed_orders.append(f"{order.name}: {order.fbr_error_message or 'Unknown error'}")

        if len(self) == 1:
            order = self[0]
            if order.fbr_status == 'posted':
                return {
                    'type': 'ir.actions.client',
                    'tag': 'display_notification',
                    'params': {
                        'title': 'FBR Integration Success',
                        'message': f'Order {order.name} successfully posted to FBR. Invoice #: {order.fbr_invoice_number}',
                        'type': 'success',
                        'sticky': False,
                    }
                }
            else:
                raise UserError(f'FBR Posting Failed for {order.name}:\n{order.fbr_error_message or "Unknown error"}')
        else:
            if failed_orders:
                raise UserError(f"Posted {posted_count} order(s) to FBR.\nFailed orders:\n" + "\n".join(failed_orders))
            return {
                'type': 'ir.actions.client',
                'tag': 'display_notification',
                'params': {
                    'title': 'FBR Integration',
                    'message': f'Successfully posted {posted_count} order(s) to FBR.',
                    'type': 'success',
                    'sticky': False,
                }
            }

    @api.model
    def cron_retry_failed_fbr_orders(self):
        """Cron job to retry failed FBR orders"""
        failed_orders = self.search([
            ('fbr_status', '=', 'failed'),
            ('config_id.fbr_pos_integration', '=', True),
        ])
        
        for order in failed_orders:
            try:
                order._send_to_fbr_pos()
                _logger.info('Retried FBR POS for order %s', order.name)
            except Exception as e:
                _logger.error('Failed to retry FBR POS for order %s: %s', order.name, str(e))
